def get_lesson_prompt(subject: str, topic: str, level: str, age: int) -> str:
    """Возвращает промпт для генерации урока по предмету"""
    subject_lower = subject.lower()
    
    for key in TECHNICAL_LESSON_PROMPTS:
        if key in subject_lower:
            return TECHNICAL_LESSON_PROMPTS[key].format(
                topic=topic,
                level=level,
                age=age
            )
    
    # Общий промпт для остальных предметов
    return f"""
    Создай образовательный урок на тему: {topic}
    
    Предмет: {subject}
    Уровень ученика: {level} класс, {age} лет
    
    Урок должен быть информативным, структурированным и интересным.
    Разделяй на логические разделы.
    Добавляй примеры и пояснения.
    
    Верни только текст урока.
    """

